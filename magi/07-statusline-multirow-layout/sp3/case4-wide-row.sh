#!/usr/bin/env bash
# Spike S3 case4: 超寬列（單列 320 字元，10 字元一格標尺：
# 0---------1---------2---------…），第 2 列為短標記列作對照，無尾隨換行。
#
# 驗什麼／預期觀察什麼：
# - 終端對超寬 statusline 列的處理：自動換行（wrap）、橫向截斷（不換行、超
#   出視窗寬度的部分被砍掉）、還是橫向捲動？
# - 若自動換行：實際換行點落在標尺的第幾格（可依標尺數字精算欄數），是否
#   與終端目前欄寬一致
# - 第 2 列（短標記列）是否仍在超寬第 1 列之後正常顯示為獨立一列（觀察超寬
#   列是否吃掉了原本屬於第 2 列的渲染位置）
ESC=$'\033'

ruler=""
for i in $(seq 0 31); do
  d=$((i % 10))
  ruler+="${d}---------"
done
# ruler 現長 320 字元（32 格 x 10 字元）

row1="${ESC}[38;5;45m${ruler}${ESC}[0m"
row2="END-OF-WIDE-ROW marker-row-2"

out="${row1}"$'\n'"${row2}"
printf '%s' "$out"
